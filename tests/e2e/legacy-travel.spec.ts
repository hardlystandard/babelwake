test('a complete legacy save preserves every world exit without confirming revised content',async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/?debug=1');await page.getByTestId('start').click();
 await expect(page.locator('.world-labels')).toHaveCSS('visibility','visible');
 await page.locator('#menu').click();
 await page.locator('#import').setInputFiles({name:'complete-0651d93-legacy.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(legacySave))});
 await expect(page.locator('#overlay')).toBeHidden();
 const content=await page.evaluate(()=>(window as unknown as{__BABELWAKE__:DebugGame}).__BABELWAKE__.content());
 const originalPages=new Set(legacySave.confirmed);
 const revisedPages=content.zones.flatMap(zone=>zone.pages.map(p=>p.id)).filter(id=>!originalPages.has(id));
 const state=()=>page.evaluate(()=>(window as unknown as{__BABELWAKE__:DebugGame}).__BABELWAKE__.getState());
 expect(await state()).toEqual(legacySave);
 expect(revisedPages.length).toBeGreaterThan(50);
 for(const [index,zone]of content.zones.entries()){
  await expect.poll(async()=>(await state()).zone).toBe(zone.id);
  expect((await state()).confirmed.filter(id=>revisedPages.includes(id))).toEqual([]);
  expect(zone.puzzle.legacyIds?.some(id=>legacySave.solved.includes(id))).toBe(true);
  expect(zone.puzzle.world?.exit).toBeTruthy();
  // Same callback as selecting the physical exit. No answer sequence, page
  // confirmation or debug.act shortcut is used to unlock the next chapter.
  await page.evaluate(id=>(window as unknown as{__BABELWAKE__:DebugGame}).__BABELWAKE__.interact(id),zone.puzzle.world!.exit!);
  if(index<content.zones.length-1)await expect.poll(async()=>(await state()).zone).toBe(content.zones[index+1].id as ZoneId);
 }
 await expect(page.locator('.ending-panel')).toBeVisible();
 await expect(page.locator('.ending-panel h2')).toHaveText('Le fil retrouvé');
 const final=await state();
 expect(final.confirmed).toEqual(legacySave.confirmed);
 expect(final.solved).toEqual(legacySave.solved);
 expect(final.guesses).toEqual(legacySave.guesses);
 expect(final.notes).toBe(legacySave.notes);
 expect(final.settings).toEqual(legacySave.settings);
 expect(errors).toEqual([]);
});
